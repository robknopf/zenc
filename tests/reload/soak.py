#!/usr/bin/env python3
"""The reload soak test: a long session of random edits, checked after each against a model.

    python3 tests/reload/soak.py [--zc ./zc] [--iterations 300] [--seed N] [--cc cc]

A module of eight functions (f0..f7, each returning its value plus helper()'s), a lambda kept
as a closure, a global counter and a literal kept from the first version. The first run
stores a pointer to each function in the host's block. Each iteration makes one random edit
(a function's value, helper's, the lambda's; a function's signature changed or back; a
function removed or back; a second lambda like the kept one added or removed; now and then
a syntax error; a new generation, whose first run stores the pointers and the closure
again), reloads (soak_host.zc), runs the module, and checks what it prints against
what the model says it must:

  - a stored pointer follows its function while it keeps its signature; once it changes or
    is gone, it stays on the last one (copied out of its version), whose call to helper
    still runs the newest helper;
  - the closure runs the newest lambda going to the same place (std/reload.zc's
    zr_lambda_match), however its body changed and whatever lambdas are added beside it;
  - the counter counts every run, across every reload; the literal reads the same.

And that memory stays bounded: from the 40th iteration on, resident memory grows by at most
--max-growth-mb. Exits 1 on the first mismatch, with the seed to repeat it.
"""
import argparse, os, random, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
NF = 8


class Model:
    def __init__(self):
        self.value = [10 * (i + 1) for i in range(NF)]
        self.sig = [0] * NF          # 0: fn() -> int, 1: fn(extra: int) -> int
        self.present = [True] * NF
        self.helper = 1
        self.k = 100                 # the kept lambda returns x + k
        self.extra_lambda = False    # a second lambda like it in setup
        self.ptr = [("follow", None)] * NF  # each stored pointer: following, or ("pinned", value)
        self.cb = ("follow", None)
        self.runs = 0
        self.gen = 1                 # when the module's generation changes, it stores them again
        self.stored_gen = 0          # the generation the state has

    def source(self, broken=False):
        out = ["// Generated by tests/reload/soak.py.",
               "struct State { p0: void*; p1: void*; p2: void*; p3: void*; p4: void*; p5: void*; "
               "p6: void*; p7: void*; cb: fn(int) -> int; msg: string; set: bool; gen: int; }",
               "let counter: int = 0;",
               f"fn helper() -> int {{ return {self.helper}; }}"]
        for i in range(NF):
            if not self.present[i]:
                continue
            params = "" if self.sig[i] == 0 else "extra: int"
            out.append(f"fn f{i}({params}) -> int {{ return {self.value[i]} + helper(); }}")
        out.append("fn setup(state: State*) {")
        if self.extra_lambda:
            out.append("    let other = fn(x: int) -> int { return x * 2; };")
            out.append('    if other(0) != 0 { println "never"; }')
        out.append(f"    state.cb = fn(x: int) -> int {{ return x + {self.k}; }};")
        out.append("}")
        out.append('@link_name("soak_step")')
        out.append("fn soak_step(state: State*) {")
        out.append(f"    if state.gen != {self.gen} {{")
        for i in range(NF):
            if self.present[i] and self.sig[i] == 0:
                out.append(f"        state.p{i} = (void*)f{i};")
        out.append('        setup(state);')
        out.append(f"        state.gen = {self.gen};")
        out.append("    }")
        out.append("    if !state.set {")
        out.append('        state.msg = "soak literal";')
        out.append("        state.set = true;")
        out.append("    }")
        out.append("    counter = counter + 1;")
        for i in range(NF):
            out.append(f"    let fp{i} = (fn*() -> int)state.p{i};")
            out.append(f"    let v{i} = fp{i}();")
            out.append(f'    println "p{i} {{v{i}}}";')
        out.append("    let c = state.cb(1);")
        out.append('    println "cb {c}";')
        out.append('    println "counter {counter}";')
        out.append('    println "msg {state.msg}";')
        out.append("}" if not broken else "")  # a missing brace: the build fails
        return "\n".join(out) + "\n"

    def expected(self):
        lines = []
        for i in range(NF):
            kind, frozen = self.ptr[i]
            v = (self.value[i] if kind == "follow" else frozen) + self.helper
            lines.append(f"p{i} {v}")
        kind, frozen = self.cb
        lines.append(f"cb {1 + (self.k if kind == 'follow' else frozen)}")
        lines.append(f"counter {self.runs}")
        lines.append("msg soak literal")
        return lines


def run_effects(m):
    """A run of a version whose generation the state hasn't seen: it stores them again."""
    if m.stored_gen != m.gen:
        for i in range(NF):
            if m.present[i] and m.sig[i] == 0:
                m.ptr[i] = ("follow", None)
        m.cb = ("follow", None)
        m.stored_gen = m.gen


def reload_effects(was, now):
    """The model after `now` loads in place of `was` (both Models, `now` a copy with the edit):
    what follows and what stays."""
    for i in range(NF):
        kind, frozen = was.ptr[i]
        if kind == "follow" and not (now.present[i] and now.sig[i] == 0):
            now.ptr[i] = ("pinned", was.value[i])  # stays on the version replaced's f{i}
        else:
            now.ptr[i] = was.ptr[i]
    # The kept lambda goes to state.cb, taking and capturing the same in every version: the
    # closure follows it, whatever its body and the lambdas beside it (zc keys a lambda by
    # where it goes: `setup#=state.cb`).
    now.cb = was.cb
    now.runs = was.runs
    now.stored_gen = was.stored_gen


def edit(m, rnd):
    """One random edit of a copy of `m`. Returns (model, broken)."""
    import copy
    n = copy.deepcopy(m)
    r = rnd.random()
    i = rnd.randrange(NF)
    if r < 0.30:
        n.value[i] = rnd.randrange(1, 1000)
    elif r < 0.40:
        n.helper = rnd.randrange(1, 50)
    elif r < 0.55:
        n.k = rnd.randrange(100, 1000)
    elif r < 0.67:
        n.sig[i] = 1 - n.sig[i]
    elif r < 0.77:
        n.present[i] = not n.present[i]
    elif r < 0.84:
        n.extra_lambda = not n.extra_lambda
    elif r < 0.92:
        n.gen += 1
    elif r < 0.95:
        return n, True
    else:  # several at once
        n.value[i] = rnd.randrange(1, 1000)
        n.helper = rnd.randrange(1, 50)
        n.k = rnd.randrange(100, 1000)
    return n, False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zc", default=os.path.join(ROOT, "zc"))
    ap.add_argument("--iterations", type=int, default=300)
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--cc", default=os.environ.get("CC", "cc"))
    ap.add_argument("--tcc-dir", default=os.environ.get("TCC_DIR"))
    ap.add_argument("--max-growth-mb", type=float, default=16.0)
    a = ap.parse_args()
    seed = a.seed if a.seed is not None else random.randrange(1 << 30)
    rnd = random.Random(seed)
    zc = os.path.abspath(a.zc)
    if not a.tcc_dir:  # zc's own (vendor/tinycc)
        r = subprocess.run([zc, "--tcc-dir"], capture_output=True, text=True)
        a.tcc_dir = r.stdout.strip() or None
    work = tempfile.mkdtemp(prefix="reload_soak_")
    windows = os.name == "nt" or sys.platform.startswith(("msys", "cygwin")) or "MINGW" in os.environ.get("MSYSTEM", "")
    exe = os.path.join(work, "soak_host" + (".exe" if windows else ""))
    libs = ["-ltcc", "-lpthread", "-lm"] + (["-Wl,--export-all-symbols"] if windows else ["-ldl", "-rdynamic"])
    dirs = []
    if a.tcc_dir:
        if os.path.exists(os.path.join(a.tcc_dir, "libtcc.h")):
            dirs = ["-I" + a.tcc_dir, "-L" + a.tcc_dir]
        else:
            dirs = ["-I" + os.path.join(a.tcc_dir, "include"), "-L" + os.path.join(a.tcc_dir, "lib")]
    host_c = os.path.join(work, "soak_host.c")
    subprocess.run([zc, "transpile", "-q", os.path.join(HERE, "soak_host.zc"), "-o", host_c], check=True)
    subprocess.run(a.cc.split() + ["-g", host_c] + dirs + libs + ["-o", exe], check=True)

    mod_dir = os.path.join(work, "mod")
    os.makedirs(mod_dir)
    mod = os.path.join(mod_dir, "soak.zc")
    host = subprocess.Popen([exe, zc, mod, os.path.join(work, "soak.c")], stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, bufsize=1)

    def ask(cmd, until):
        host.stdin.write(cmd + "\n")
        host.stdin.flush()
        got = []
        while True:
            line = host.stdout.readline()
            if not line:
                return got, None
            line = line.rstrip("\r\n")
            if until(line):
                return got, line
            got.append(line)

    def fail(msg):
        print(f"FAIL (seed {seed}, iteration {it}): {msg}")
        print(f"  repeat: python3 tests/reload/soak.py --seed {seed} --iterations {a.iterations}")
        host.kill()
        sys.exit(1)

    m = Model()
    rss = []
    counts = {"loaded": 0, "failed": 0}
    it = 0
    for it in range(a.iterations + 1):
        if it == 0:
            n, broken = m, False
        else:
            n, broken = edit(m, rnd)
        with open(mod, "w") as f:
            f.write(n.source(broken))
        _, answer = ask("build", lambda l: l.startswith(("loaded", "failed")))
        if answer is None:
            fail("the host ended")
        if broken:
            if not answer.startswith("failed"):
                fail(f"a version that doesn't build: {answer}")
            counts["failed"] += 1
        else:
            if not answer.startswith("loaded"):
                fail("a version that builds wasn't loaded")
            counts["loaded"] += 1
            if it > 0:
                reload_effects(m, n)
            m = n
        _, mem = ask("mem", lambda l: l.startswith("rss"))
        rss.append(int(mem.split()[1]))
        m.runs += 1
        run_effects(m)
        out, end = ask("run", lambda l: l in ("ran", "crashed"))
        if end != "ran":
            fail(f"the module crashed ({end}); it printed: {out}")
        want = m.expected()
        if out != want:
            diff = [f"    {w!r} expected, got {g!r}" for w, g in zip(want, out) if w != g]
            fail("the module printed something else:\n" + "\n".join(diff or [f"    {out}"]))
    ask("quit", lambda l: True)
    host.wait(timeout=30)
    base = max(rss[:40]) if len(rss) > 40 else max(rss)
    growth = (max(rss[40:]) - base) / 1024 if len(rss) > 40 else 0.0
    shutil.rmtree(work, ignore_errors=True)
    print(f"soak: {a.iterations} edits (seed {seed}): {counts['loaded']} loaded, {counts['failed']} didn't "
          f"build (as meant); pointers pinned: {sum(1 for k, _ in m.ptr if k == 'pinned')} of {NF}, "
          f"closure {m.cb[0]}; memory {rss[0] // 1024} MB at the start, {max(rss) // 1024} MB at most, "
          f"{growth:+.1f} MB after the 40th")
    if growth > a.max_growth_mb:
        print(f"FAIL (seed {seed}): memory grew {growth:.1f} MB after the 40th iteration (at most {a.max_growth_mb})")
        sys.exit(1)
    print("PASS")


if __name__ == "__main__":
    main()
